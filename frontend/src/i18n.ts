function initialLanguage(): DisplayLanguage {
  if (typeof window === 'undefined') return 'en'
  const stored = readStoredValue(DISPLAY_LANGUAGE_STORAGE_KEY)
  if (stored === 'zh' || stored === 'en') return stored
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const i18n = i18next.createInstance()

void i18n.use(initReactI18next).init({
  lng: initialLanguage(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  resources: {
    en: { translation: {} },
    zh: { translation: zh },
  },
  returnNull: false,
})

export function useDocSeekTranslation() {
  return useTranslation(undefined, { i18n })
}

export async function changeDisplayLanguage(
  language: DisplayLanguage,
  options: { persistProfile?: boolean } = {},
): Promise<void> {
  void options.persistProfile
  if (typeof window !== 'undefined') {
    writeStoredValue(DISPLAY_LANGUAGE_STORAGE_KEY, language)
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
  }
  await i18n.changeLanguage(language)
}

export function displayLanguageName(): 'English' | 'Chinese' {
  const stored = typeof window === 'undefined'
    ? i18n.language
    : readStoredValue(DISPLAY_LANGUAGE_STORAGE_KEY) || i18n.language
  return String(stored).toLowerCase().startsWith('zh') ? 'Chinese' : 'English'
}

if (typeof document !== 'undefined') {
  document.documentElement.lang = i18n.language === 'zh' ? 'zh-CN' : 'en'
}
